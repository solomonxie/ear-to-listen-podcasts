def main():
    names = set(COMMON_TERMS) | {w for book, aliases in BIBLE_BOOKS.items() for w in [book, *aliases]}
    names |= column(NAMES_TSV_URL, "\t", 5) | column(DICT_CSV_URL, ";", 2)
    words = set(CHRISTIAN_TERMS) | set(sorted(names)[:NAMES_CAP])
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(sorted(words)))
    print(f"wrote {OUT}: {len(words)} terms")


def column(url, delimiter, idx):
    text = urllib.request.urlopen(url).read().decode("utf-8")
    return {row[idx].strip() for row in csv.reader(text.splitlines(), delimiter=delimiter)
            if len(row) > idx and row[idx].strip() and all("\u4e00" <= c <= "\u9fff" for c in row[idx].strip())}


if __name__ == "__main__":
    main()
